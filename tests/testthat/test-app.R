test_that("the app runs a demo from data to report", {
  skip_on_cran()
  skip_if_not_installed("shinytest2")
  skip_if_not_installed("chromote")
  skip_if(is.null(chromote::find_chrome()), "Chrome not found")
  app <- shinytest2::AppDriver$new(run_app(), name = "smoke", height = 900, width = 1300,
                                   load_timeout = 60000, timeout = 30000)
  on.exit(app$stop())
  app$run_js("Shiny.setInputValue('goto_step', 'data', {priority: 'event'})")
  app$set_inputs(`data-demo` = "binary")
  app$click("data-load_demo")
  app$wait_for_idle()
  app$run_js("Shiny.setInputValue('goto_step', 'qc', {priority: 'event'})")
  app$wait_for_idle()
  app$click("qc-apply")
  app$wait_for_idle()
  app$run_js("Shiny.setInputValue('goto_step', 'distance', {priority: 'event'})")
  app$wait_for_idle()
  app$click("distance-go")
  app$wait_for_idle()
  app$run_js("Shiny.setInputValue('goto_step', 'tree', {priority: 'event'})")
  app$wait_for_idle()
  app$click("tree-go")
  app$wait_for_idle()
  app$run_js("Shiny.setInputValue('goto_step', 'report', {priority: 'event'})")
  app$wait_for_idle()
  stepper <- app$get_text("#stepper")
  expect_match(stepper, "30 samples, 60 markers")
  expect_match(stepper, "UPGMA")
  report <- app$get_download("report-report")
  expect_match(paste(readLines(report), collapse = ""), "Clusnalyst report")
})
